/**
 * Stamps a build version into the app, so a running tab can tell it is out of date.
 *
 * Writes two files from ONE value:
 *   public/version.json   — served alongside the app; polled by the running tab.
 *   src/lib/buildVersion.js — compiled INTO the bundle, so the JS knows its own version.
 *
 * Comparing those two is what detects a deploy. The alternative — treating the first
 * fetched version as the baseline — misses the case where a tab loads a cached HTML
 * shell after a deploy has already landed, because then the "baseline" is already the
 * new version and the stale bundle never reports itself.
 *
 * Runs from the `prebuild` npm hook, so `npm run build` always produces a fresh stamp.
 * src/lib/buildVersion.js is committed with a placeholder so a fresh clone can build
 * before this script has ever run.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Millisecond build timestamp: monotonic, needs no VCS, and differs for every deploy.
const version = new Date().toISOString();

mkdirSync(join(root, 'public'), { recursive: true });
writeFileSync(
  join(root, 'public', 'version.json'),
  `${JSON.stringify({ version }, null, 2)}\n`,
);

mkdirSync(join(root, 'src', 'lib'), { recursive: true });
writeFileSync(
  join(root, 'src', 'lib', 'buildVersion.js'),
  `// GENERATED by scripts/write-build-version.mjs on each build — do not edit by hand.\n`
    + `export const BUILD_VERSION = ${JSON.stringify(version)};\n`,
);

console.log(`[build-version] ${version}`);
